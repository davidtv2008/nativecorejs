/**
 * Pure Component Builder codegen / parse helpers.
 * Usable from Node tests and the browser builder (no DOM dependency).
 */

export const BUILDER_OWNED_MARKER = '@nativecore-builder-owned true';
export const BUILDER_BANNER = 'Auto-generated by NativeCore Component Builder';

const BOOL_ATTRS = new Set([
    'disabled', 'readonly', 'required', 'checked', 'selected', 'open', 'loading',
    'multiple', 'autofocus', 'hidden', 'novalidate', 'controls', 'muted', 'loop',
    'playsinline', 'draggable', 'contenteditable', 'full-width', 'clearable',
    'dismissible', 'clickable', 'dot',
]);

export function defaultLayout() {
    return {
        direction: 'column',
        wrap: 'nowrap',
        alignItems: 'flex-start',
        justifyContent: 'flex-start',
        gap: '12px',
        padding: '16px',
    };
}

export function toClassName(tag) {
    return String(tag || '')
        .split('-')
        .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
        .join('');
}

export function uid() {
    return Math.random().toString(36).slice(2, 9);
}

export function isBuilderOwned(code) {
    return typeof code === 'string'
        && code.includes(BUILDER_BANNER)
        && code.includes(BUILDER_OWNED_MARKER);
}

export function createEmptyState() {
    return {
        componentTag: 'my-component',
        componentClass: 'MyComponent',
        componentDesc: '',
        useShadowDOM: true,
        observedAttrs: [],
        children: [],
        layout: defaultLayout(),
        events: [],
        selectedChildId: null,
        dragSourceId: null,
        dragOverId: null,
    };
}

function inferAttrType(attrName) {
    return BOOL_ATTRS.has(attrName) ? 'bool' : 'text';
}

function escapeAttr(value) {
    return String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
}

function parseAttrString(attrStr) {
    const attrs = {};
    let classList = '';
    let nodeId = '';
    const re = /([^\s=]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'>]+)))?/g;
    let m;
    while ((m = re.exec(attrStr || '')) !== null) {
        const name = m[1];
        if (!name || name === '/') continue;
        const raw = m[2] ?? m[3] ?? m[4];
        if (name === 'class') {
            classList = raw ?? '';
            continue;
        }
        if (name === 'id') {
            nodeId = raw ?? '';
            continue;
        }
        if (raw === undefined) {
            attrs[name] = { type: 'bool', value: true };
        } else {
            const type = inferAttrType(name);
            attrs[name] = type === 'bool'
                ? { type: 'bool', value: true }
                : { type: 'text', value: raw };
        }
    }
    return { attrs, classList, nodeId };
}

/** Parse flat top-level tags from a template body (no nested custom trees). */
export function parseChildrenHTML(body) {
    const children = [];
    const cleaned = String(body || '').replace(/<style>[\s\S]*?<\/style>/gi, '').trim();
    const re = /<([a-zA-Z][\w-]*)((?:\s[^>]*)?)(?:\/>|>([\s\S]*?)<\/\1>)/g;
    let m;
    while ((m = re.exec(cleaned)) !== null) {
        const tag = m[1].toLowerCase();
        const { attrs, classList, nodeId } = parseAttrString(m[2] || '');
        children.push({
            id: uid(),
            tag,
            attrs,
            slotContent: (m[3] || '').trim(),
            classList,
            nodeId,
        });
    }
    return children;
}

function renderChildrenHTML(children) {
    const indent = '            ';
    if (!children.length) return `${indent}<slot></slot>`;
    return children.map((c) => {
        const attrs = Object.entries(c.attrs || {})
            .filter(([, attr]) => (attr.type === 'bool' ? Boolean(attr.value) : String(attr.value) !== ''))
            .map(([k, attr]) => (attr.type === 'bool' ? ` ${k}` : ` ${k}="${escapeAttr(attr.value)}"`))
            .join('');
        const classAttr = c.classList ? ` class="${escapeAttr(c.classList)}"` : '';
        const idAttr = c.nodeId ? ` id="${escapeAttr(c.nodeId)}"` : '';
        const selfClose = ['img', 'input', 'hr', 'br'].includes(c.tag);
        if (selfClose) return `${indent}<${c.tag}${idAttr}${classAttr}${attrs} />`;
        return `${indent}<${c.tag}${idAttr}${classAttr}${attrs}>${c.slotContent || ''}</${c.tag}>`;
    }).join('\n');
}

function layoutCSS(layout) {
    const l = { ...defaultLayout(), ...(layout || {}) };
    return [
        'display: flex',
        `flex-direction: ${l.direction}`,
        l.wrap !== 'nowrap' ? `flex-wrap: ${l.wrap}` : '',
        l.alignItems !== 'flex-start' ? `align-items: ${l.alignItems}` : '',
        l.justifyContent !== 'flex-start' ? `justify-content: ${l.justifyContent}` : '',
        `gap: ${l.gap}`,
        `padding: ${l.padding}`,
    ].filter(Boolean).map((r) => `                ${r};`).join('\n');
}

function parseLayoutFromHost(hostCss) {
    const layout = defaultLayout();
    const pick = (prop, fallback) => {
        const m = hostCss.match(new RegExp(`${prop}\\s*:\\s*([^;]+);`));
        return m ? m[1].trim() : fallback;
    };
    layout.direction = pick('flex-direction', layout.direction);
    layout.wrap = pick('flex-wrap', layout.wrap);
    layout.alignItems = pick('align-items', layout.alignItems);
    layout.justifyContent = pick('justify-content', layout.justifyContent);
    layout.gap = pick('gap', layout.gap);
    layout.padding = pick('padding', layout.padding);
    return layout;
}

/**
 * @param {object} state
 * @param {'ts'|'js'} lang
 */
export function generateBuilderCode(state, lang = 'ts') {
    const s = state || createEmptyState();
    // lang reserved for future dialect splits; current IR emits valid TS and JS.
    const obsNames = (s.observedAttrs || []).map((a) => `'${a.name}'`).join(', ');
    const obsBlock = obsNames
        ? `\n    static observedAttributes = [${obsNames}];\n`
        : '';

    const childrenHTML = renderChildrenHTML(s.children || []);
    const css = layoutCSS(s.layout);

    const attrChangedBlock = (s.observedAttrs || []).length > 0
        ? `
    attributeChangedCallback(name, _old, _new) {
        if (!this._mounted) return;
        this.render();
    }
`
        : '';

    const onMountListeners = (s.events || []).map((ev) => {
        const payloadKeys = (ev.payload || [])
            .filter((p) => p.key)
            .map((p) => `                    ${p.key}: null /* set payload value */`)
            .join(',\n');
        const payloadArg = payloadKeys ? `{\n${payloadKeys}\n                }` : '{}';
        const options = [];
        if (!ev.bubbles) options.push('bubbles: false');
        if (!ev.composed) options.push('composed: false');
        if (ev.cancelable) options.push('cancelable: true');
        const optionsArg = options.length ? `, { ${options.join(', ')} }` : '';
        if (ev.trigger && ev.triggerTag) {
            return `        this.on('${ev.trigger}', '${ev.triggerTag}', () => {\n            this.emit('${ev.name}', ${payloadArg}${optionsArg});\n        });`;
        }
        return `        // TODO: wire '${ev.name}'\n        // this.emit('${ev.name}', ${payloadArg}${optionsArg});`;
    }).join('\n\n');

    const onMountBlock = onMountListeners
        ? `\n    onMount() {\n${onMountListeners}\n    }\n`
        : '';

    const defaultsBlock = (s.observedAttrs || []).length > 0
        ? `${s.observedAttrs.map((a) => {
            const camel = a.name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
            return `        const ${camel} = this.attr('${a.name}'${a.defaultValue ? `, '${a.defaultValue}'` : ''});`;
        }).join('\n')}\n\n`
        : '';

    const descComment = s.componentDesc ? `\n * ${s.componentDesc}` : '';
    const date = new Date().toLocaleDateString();

    return `/**${descComment}
 * ${BUILDER_BANNER}
 * ${BUILDER_OWNED_MARKER}
 * ${date}
 */
import { CoreComponent, defineComponent } from '@core/component.js';
import { html } from '@core-utils/templates.js';

export class ${s.componentClass} extends CoreComponent {
    static useShadowDOM = ${s.useShadowDOM !== false};
${obsBlock}
    template() {
${defaultsBlock}        return html\`
            <style>
                :host {
${css}
                }
            </style>
${childrenHTML}
        \`;
    }
${onMountBlock}${attrChangedBlock}}

defineComponent('${s.componentTag}', ${s.componentClass});
`;
}

/**
 * @param {string} code
 */
export function parseBuilderSource(code) {
    const warnings = [];
    const state = createEmptyState();
    const src = String(code || '');

    const defineMatch = src.match(/defineComponent\(\s*['"]([^'"]+)['"]/);
    if (defineMatch) {
        state.componentTag = defineMatch[1];
        state.componentClass = toClassName(defineMatch[1]);
    } else {
        warnings.push('Could not find defineComponent(...) — tag may be wrong.');
    }

    const classMatch = src.match(/export\s+class\s+(\w+)/);
    if (classMatch) state.componentClass = classMatch[1];

    const descMatch = src.match(/\/\*\*[\s\S]*?\*\s+([^\n*]+)\s*\n\s*\*\s+Auto-generated by NativeCore Component Builder/);
    if (descMatch && !descMatch[1].includes(BUILDER_OWNED_MARKER) && !descMatch[1].includes('Auto-generated')) {
        state.componentDesc = descMatch[1].trim();
    }

    if (/static\s+useShadowDOM\s*=\s*false/.test(src)) {
        state.useShadowDOM = false;
    }

    const obsMatch = src.match(/static\s+(?:get\s+)?observedAttributes(?:\s*\(\s*\)\s*\{\s*return)?\s*[=]?\s*\[([^\]]*)\]/);
    if (obsMatch) {
        const names = [...obsMatch[1].matchAll(/['"]([^'"]+)['"]/g)].map((m) => m[1]);
        state.observedAttrs = names.map((name) => {
            const camel = name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
            const defMatch =
                src.match(new RegExp(`this\\.attr\\(\\s*['"]${name}['"]\\s*,\\s*['"]([^'"]*)['"]`))
                || src.match(new RegExp(`(?:const|let)\\s+${camel}\\s*=\\s*this\\.attr\\(\\s*['"]${name}['"]\\s*,\\s*['"]([^'"]*)['"]`));
            return { name, defaultValue: defMatch ? defMatch[1] : '' };
        });
    }

    const htmlMatch = src.match(/return\s+html`([\s\S]*?)`\s*;/);
    if (!htmlMatch) {
        warnings.push('Could not find html`…` template — canvas children are empty.');
    } else {
        let body = htmlMatch[1];
        const hostMatch = body.match(/:host\s*\{([^}]*)\}/);
        if (hostMatch) state.layout = parseLayoutFromHost(hostMatch[1]);
        state.children = parseChildrenHTML(body);
    }

    const eventRegex = /this\.on\(\s*['"]([^'"]+)['"]\s*,\s*['"]([^'"]+)['"]\s*,\s*\(\)\s*=>\s*\{\s*this\.emit\(\s*['"]([^'"]+)['"]\s*,\s*\{([^}]*)\}([\s\S]*?)\)\s*;/g;
    let evMatch;
    while ((evMatch = eventRegex.exec(src)) !== null) {
        const [, trigger, triggerTag, name, payloadBody, optionsTail] = evMatch;
        const payload = [...payloadBody.matchAll(/([A-Za-z_][\w]*)\s*:/g)]
            .map((m) => m[1])
            .filter((key) => key !== 'TODO' && key !== 'null')
            .map((key) => ({ key, type: 'string' }));
        state.events.push({
            id: uid(),
            name,
            trigger,
            triggerTag,
            payload,
            bubbles: !/bubbles\s*:\s*false/.test(optionsTail),
            composed: !/composed\s*:\s*false/.test(optionsTail),
            cancelable: /cancelable\s*:\s*true/.test(optionsTail),
        });
    }

    if (!src.includes(BUILDER_BANNER)) {
        warnings.push('This file was not created by the Component Builder — some structure may not round-trip.');
    } else if (!src.includes(BUILDER_OWNED_MARKER)) {
        warnings.push('Missing builder ownership marker — treat as possibly hand-edited.');
    }

    return { state, warnings, builderOwned: isBuilderOwned(src) };
}

/** Normalize volatile fields for deep equality in tests. */
export function normalizeState(state) {
    return {
        componentTag: state.componentTag,
        componentClass: state.componentClass,
        componentDesc: state.componentDesc || '',
        useShadowDOM: state.useShadowDOM !== false,
        observedAttrs: (state.observedAttrs || []).map((a) => ({
            name: a.name,
            defaultValue: a.defaultValue || '',
        })),
        children: (state.children || []).map((c) => ({
            tag: c.tag,
            attrs: c.attrs || {},
            slotContent: c.slotContent || '',
            classList: c.classList || '',
            nodeId: c.nodeId || '',
        })),
        layout: { ...defaultLayout(), ...(state.layout || {}) },
        events: (state.events || []).map((e) => ({
            name: e.name,
            trigger: e.trigger,
            triggerTag: e.triggerTag,
            payload: (e.payload || []).map((p) => ({ key: p.key, type: p.type || 'string' })),
            bubbles: e.bubbles !== false,
            composed: e.composed !== false,
            cancelable: !!e.cancelable,
        })),
    };
}
